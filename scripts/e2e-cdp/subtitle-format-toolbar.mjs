// Run with a loaded project in the isolated launcher; queue its saved copy for reopening.
// Arguments: fresh saved .autosub path, fresh exported ASS path (launcher save destination).
import assert from 'node:assert/strict'
import fs from 'node:fs'
import { connect } from './cdp.mjs'

const [savedProject, exportedAss] = process.argv.slice(2)
assert(savedProject && exportedAss, 'Pass isolated save and export destinations')
const c = await connect()
const read = expression => c.evaluate(expression)
async function click(selector) {
  const p = await read(`(() => { const el=document.querySelector(${JSON.stringify(selector)}); if(!el) throw Error('Missing control'); const r=el.getBoundingClientRect(); return {x:r.x+r.width/2,y:r.y+r.height/2}; })()`)
  await c.click(p.x,p.y)
}
async function button(text) {
  const p = await read(`(() => { const el=[...document.querySelectorAll('button')].find(b=>b.textContent.trim()===${JSON.stringify(text)}); if(!el || el.disabled) throw Error('Missing button'); const r=el.getBoundingClientRect(); return {x:r.x+r.width/2,y:r.y+r.height/2}; })()`)
  await c.click(p.x,p.y)
}
async function input(label,value) {
  await read(`(() => {const el=document.querySelector('input[aria-label="${label}"]');el.focus();Object.getOwnPropertyDescriptor(HTMLInputElement.prototype,'value').set.call(el,${JSON.stringify(String(value))});el.dispatchEvent(new Event('input',{bubbles:true}));})()`)
  await c.sleep(80)
}
async function escape() {
  await c.send('Input.dispatchKeyEvent',{type:'keyDown',key:'Escape',code:'Escape',windowsVirtualKeyCode:27})
  await c.send('Input.dispatchKeyEvent',{type:'keyUp',key:'Escape',code:'Escape',windowsVirtualKeyCode:27})
  await c.sleep(80)
}
async function wait(check,message) {
  for(let i=0;i<100;i++) {if(await check()) return; await c.sleep(100)}
  throw Error(message)
}
const preview = () => read(`(() => { const e=document.querySelector('.preview-subtitle-text');return {text:e.textContent,fontSize:e.style.fontSize,fontWeight:e.style.fontWeight,color:e.style.color,background:e.style.background,left:e.style.left,bottom:e.style.bottom,textShadow:e.style.textShadow,padding:e.style.padding}; })()`)
try {
  await button('서식')
  await read(`(() => {const el=document.querySelector('.preview-seek');el.focus();Object.getOwnPropertyDescriptor(HTMLInputElement.prototype,'value').set.call(el,13);el.dispatchEvent(new Event('input',{bubbles:true}));el.dispatchEvent(new Event('change',{bubbles:true}));})()`)
  await c.sleep(300)
  assert((await preview()).text.length>0)
  const before=await read(`({duration:document.querySelector('.preview-seek').max,time:document.querySelector('video').currentTime,text:document.querySelector('.preview-subtitle-text').textContent})`)
  assert.equal(await read(`document.querySelectorAll('.subtitle-format-toolbar input[type="range"]').length`),0)
  await click('button[aria-label="글자 크기"]')
  await button('110')
  assert.equal((await preview()).fontSize,'110px')
  await click('button[aria-label="글자 크기"]')
  await input('글자 크기','')
  await c.press('Enter')
  assert.equal((await preview()).fontSize,'110px','Blank typing must not become zero')
  await input('글자 크기',999)
  await c.press('Enter')
  assert.equal((await preview()).fontSize,'300px','Out-of-range input clamps on commit')
  await input('글자 크기',42)
  await escape()
  assert.equal(await read(`document.activeElement.getAttribute('aria-label')`),'글자 크기')
  await click('button[aria-label="굵게"]')
  assert.equal((await preview()).fontWeight,'400')
  // Space on a formatting button must activate it without toggling media playback.
  await c.press('Space')
  assert.equal((await preview()).fontWeight,'700')
  assert(await read(`document.querySelector('video').paused`))
  await click('button[aria-label="글자 색상"]')
  await click('button[aria-label="글자색 #fef08a"]')
  await input('글자색 HEX','#12abcd')
  await c.press('Enter')
  assert.equal((await preview()).color,'rgb(18, 171, 205)')
  await input('글자색 HEX','invalid')
  await c.press('Enter')
  assert.equal((await preview()).color,'rgb(18, 171, 205)')
  await click('button[aria-label="테두리"]')
  assert.equal(await read(`document.querySelectorAll('.subtitle-format-popup').length`),1)
  await click('button[aria-label="테두리 #ffffff"]')
  await input('테두리 두께',4)
  assert((await preview()).textShadow.includes('4px'))
  await button('테두리 없음')
  assert.equal(await read(`document.querySelector('input[aria-label="테두리 두께"]').value`),'0')
  await input('테두리 두께',3)
  await click('button[aria-label="배경"]')
  await click('button[aria-label="배경 #164e63"]')
  await input('배경 불투명도',80)
  await input('배경 여백',120)
  assert.equal((await preview()).background,'rgba(22, 78, 99, 0.8)')
  await button('배경 없음')
  assert.equal((await preview()).background,'rgba(22, 78, 99, 0)')
  await input('배경 불투명도',80)
  await click('button[aria-label="자막 위치"]')
  await button('오른쪽')
  assert.equal((await preview()).left,'75%')
  await button('가운데')
  await input('상하 위치',12)
  assert.equal((await preview()).bottom,'12%')
  await escape()
  const after=await read(`({duration:document.querySelector('.preview-seek').max,time:document.querySelector('video').currentTime,text:document.querySelector('.preview-subtitle-text').textContent})`)
  assert.deepEqual(after,before,'Formatting must not alter playback or caption text')
  const styledPreview=await preview()
  await button('다른 이름으로 저장')
  await wait(()=>fs.existsSync(savedProject),'Project save timed out')
  const saved=JSON.parse(fs.readFileSync(savedProject,'utf8'))
  for(const [key,value] of Object.entries({fontSize:42,fontWeight:700,textColor:'#12abcd',strokeColor:'#ffffff',strokeWidth:3,bgColor:'#164e63',bgOpacity:80,bgPaddingPct:120,x:50,y:12})) assert.equal(saved.subtitleStyle[key],value,`${key} not saved`)
  await read(`(() => {const el=document.querySelector('.preview-export-format');Object.getOwnPropertyDescriptor(HTMLSelectElement.prototype,'value').set.call(el,'ass');el.dispatchEvent(new Event('change',{bubbles:true}));})()`)
  await button('내보내기')
  await wait(()=>fs.existsSync(exportedAss),'ASS export timed out')
  const ass=fs.readFileSync(exportedAss,'utf8')
  assert(ass.includes(`Style: Default,${saved.subtitleStyle.fontFamily},42,&H00CDAB12`),'Export did not use selected font size and color')
  await button('불러오기')
  await c.sleep(1200)
  await wait(async()=>await read(`document.querySelector('.subtitle-format-toolbar button[aria-label="글자 크기"]').textContent.includes('42')`),'Style not restored')
  await read(`(() => {const el=document.querySelector('.preview-seek');el.focus();Object.getOwnPropertyDescriptor(HTMLInputElement.prototype,'value').set.call(el,13);el.dispatchEvent(new Event('input',{bubbles:true}));el.dispatchEvent(new Event('change',{bubbles:true}));})()`)
  await c.sleep(300)
  assert.deepEqual(await preview(),styledPreview,'Preview style changed on reopening')
  await c.send('Emulation.setDeviceMetricsOverride',{width:1000,height:760,deviceScaleFactor:1,mobile:false})
  await click('button[aria-label="자막 위치"]')
  assert(await read(`(() => { const r=document.querySelector('.subtitle-format-popup').getBoundingClientRect();return r.left>=0 && r.right<=innerWidth && r.bottom<=innerHeight; })()`),'Popup is clipped')
  await button('홈')
  assert.equal(await read(`document.querySelectorAll('.subtitle-format-popup').length`),0,'Popup survived leaving format tab')
  console.log('PASS: presets, numeric/HEX input, keyboard, preview, playback invariance, project reopen, ASS export, narrow-window popup')
} finally { c.close() }
